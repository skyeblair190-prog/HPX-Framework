CREATE TABLE IF NOT EXISTS hp4_garages (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(40) NOT NULL,
    types VARCHAR(255) NOT NULL,
    x DOUBLE NOT NULL,
    y DOUBLE NOT NULL,
    z DOUBLE NOT NULL,
    radius FLOAT NOT NULL DEFAULT 40,
    PRIMARY KEY (id)
);

CREATE TABLE IF NOT EXISTS hp4_garage_spots (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    garage_id INT UNSIGNED NOT NULL,
    label VARCHAR(40) NOT NULL DEFAULT '',
    x DOUBLE NOT NULL,
    y DOUBLE NOT NULL,
    z DOUBLE NOT NULL,
    h FLOAT NOT NULL,
    PRIMARY KEY (id),
    KEY idx_spot_garage (garage_id),
    CONSTRAINT fk_hp4_spot_garage FOREIGN KEY (garage_id) REFERENCES hp4_garages (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS hp4_vehicles (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    plate VARCHAR(8) NOT NULL,
    model BIGINT NOT NULL,
    label VARCHAR(40) NOT NULL DEFAULT '',
    vtype VARCHAR(16) NOT NULL DEFAULT 'automobile',
    garage_id INT UNSIGNED NULL,
    spot_id INT UNSIGNED NULL,
    x DOUBLE NOT NULL,
    y DOUBLE NOT NULL,
    z DOUBLE NOT NULL,
    h FLOAT NOT NULL DEFAULT 0,
    engine FLOAT NOT NULL DEFAULT 1000,
    body FLOAT NOT NULL DEFAULT 1000,
    locked TINYINT NOT NULL DEFAULT 0,
    props LONGTEXT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'active',
    owner VARCHAR(50) NULL,
    updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_hp4_plate (plate),
    UNIQUE KEY uq_hp4_spot (spot_id)
)
